/**
 * Get translated UI string with reliable fallback
 */
export function getUIText(key: string, langCode: string): string {
  if (UI_TRANSLATIONS[langCode] && UI_TRANSLATIONS[langCode][key]) {
    return UI_TRANSLATIONS[langCode][key];
  }
  if (UI_TRANSLATIONS.en[key]) {
    return UI_TRANSLATIONS.en[key];
  }
  return key;
}

/**
 * Text-to-Speech audio reader for low literacy assistance
 */
export function speakInstruction(text: string, langCode: string): boolean {
  if (typeof window === 'undefined' || !('speechSynthesis' in window)) {
    return false;
  }

  try {
    window.speechSynthesis.cancel(); // Stop any pending utterances
    const utterance = new SpeechSynthesisUtterance(text);
    const langObj = GLOBAL_LANGUAGES.find((l) => l.code === langCode);
    utterance.lang = langObj?.bcp47 || 'en-US';
    utterance.rate = 0.95; // Slightly slower, very clear pace
    window.speechSynthesis.speak(utterance);
    return true;
  } catch (e) {
    console.warn('Speech synthesis error:', e);
    return false;
  }
}
